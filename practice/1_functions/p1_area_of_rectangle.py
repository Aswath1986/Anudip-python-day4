"""
Practice 1: Area of a rectangle
A function takes inputs (length, width) and RETURNS an answer.
"""

def area(length, width):
    return length * width


print("Area of 5 x 3 room   :", area(5, 3))
print("Area of 10 x 12 hall :", area(10, 12))

